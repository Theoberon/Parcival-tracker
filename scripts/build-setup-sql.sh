#!/usr/bin/env bash
# Builds the numbered files you paste into the Supabase SQL editor, in order (no CLI needed):
#   1-schema  2-functions  3-security  4-login-delay  5-titles  6-starting-data
# Each part is cut only between whole migrations, so every file is complete and runs on its own.
# 0-start-over, 7-create-owner and 8-schedule-cleanup are written by hand.
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/setup
mkdir -p "$out"; rm -f "$out"/[1-6]-*.sql

# part file                 | title                                   | sources
parts=(
  "1-schema.sql|tables, rules that guard the data, audit log|20261009000100_schema.sql 20261009000700_multi_org.sql"
  "2-functions.sql|the actions the site can perform (approve, withdraw, standings ...)|20261009000200_rpc.sql"
  "3-security.sql|who can read what (row-level security), private storage bucket|20261009000300_security.sql"
  "4-login-delay.sql|growing delay after failed logins|20261009000400_login_throttle.sql"
  "5-titles.sql|contestant titles, organisation isolation, sequential contest retention, and cross-organisation leaderboards|20261009000500_member_title.sql 20261009000600_leaderboard_hides_title.sql 20261024124552_leaderboard_category_counts.sql 20261024152538_organization_isolation.sql 20261024163531_platform_owner_org_management.sql 20261025064413_end_contest_early.sql 20261025070355_organization_next_contest.sql 20261026093834_all_organization_leaderboards.sql"
)
# A friendly check at the top of each part: is the previous part done, and has this one not already been run?
check() { # $1 = SQL condition that must be TRUE for the failure, $2 = message
  printf "do \$\$ begin\n  if %s then\n    raise exception '%s';\n  end if;\nend \$\$;\n" "$1" "$2"
}
preflight() {
  echo "-- Safety check: stops with a plain message if a part was skipped or run twice."
  if [ "$1" != "1" ]; then check "to_regclass('public.submissions') is null" "The parts must be run in order. Start with part 1 (1-schema.sql): the tables do not exist yet."; fi
  case "$1" in
    1) check "to_regclass('public.contests') is not null" "Part 1 was already run (the tables exist). Continue with part 2. To start completely over on a project with no real data, run 0-start-over.sql first.";;
    2) check "to_regprocedure('public.approve_submission(uuid)') is not null" "Part 2 was already run. Continue with part 3.";;
    3) check "to_regprocedure('public.approve_submission(uuid)') is null" "Run part 2 (2-functions.sql) first."
       check "(select relrowsecurity from pg_class where oid = 'public.submissions'::regclass)" "Part 3 was already run. Continue with part 4.";;
    4) check "not (select relrowsecurity from pg_class where oid = 'public.submissions'::regclass)" "Run part 3 (3-security.sql) first."
       check "to_regclass('public.login_failures') is not null" "Part 4 was already run. Continue with part 5.";;
    5) check "to_regclass('public.login_failures') is null" "Run part 4 (4-login-delay.sql) first."
       check "exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'members' and column_name = 'title')" "Part 5 was already run. Continue with part 6.";;
  esac
}
n=${#parts[@]}; used=""
for entry in "${parts[@]}"; do
  IFS='|' read -r file title sources <<<"$entry"
  {
    echo "-- Contest Scoreboard database setup, part ${file%%-*} of 6: $title."
    echo "-- Paste this WHOLE file into the Supabase SQL editor (New query) and press Run. Then do the next number."
    echo "-- Generated by scripts/build-setup-sql.sh from supabase/migrations. Do not edit by hand."
    preflight "${file%%-*}"
    for s in $sources; do
      printf '\n-- ----- %s -----\n' "$s"; cat "supabase/migrations/$s"; used="$used $s"
    done
    printf '\n-- END OF PART %s. If this line is not the last line in the editor, the paste was cut short: clear the editor and copy the file again in one piece.\n' "${file%%-*}"
  } > "$out/$file"
done
# every migration must belong to a part
for f in supabase/migrations/*.sql; do
  case "$used" in *"$(basename "$f")"*) ;; *) echo "ERROR: $(basename "$f") is not assigned to a setup part in scripts/build-setup-sql.sh" >&2; exit 1;; esac
done
{
  echo "-- Contest Scoreboard database setup, part 6 of 6: the starting contest and its four categories."
  echo "-- Paste this WHOLE file into the Supabase SQL editor and press Run. Then do 7-create-owner.sql."
  echo "-- Generated by scripts/build-setup-sql.sh from supabase/seed.sql. Do not edit by hand."
  echo "-- Safety check: stops with a plain message if part 5 has not been run."
  check "to_regclass('public.submissions') is null" "The parts must be run in order. Start with part 1 (1-schema.sql): the tables do not exist yet."
  check "not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'members' and column_name = 'title')" "Run part 5 (5-titles.sql) first."
  echo
  sed '/^-- Owner admin placeholder/,$d' supabase/seed.sql
  printf '\n-- END OF PART 6. If this line is not the last line in the editor, the paste was cut short: clear the editor and copy the file again in one piece.\n'
} > "$out/6-starting-data.sql"
wc -l "$out"/[1-6]-*.sql | sed 's#supabase/setup/##'
